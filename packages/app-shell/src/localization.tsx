export const messages = { en, es, ht, fr, 'zh-CN': zhCN } satisfies Record<Language, Record<TranslationKey, string>>;

const localeByLanguage: Record<Language, string> = {
  en: 'en-US',
  es: 'es-US',
  ht: 'ht',
  fr: 'fr-FR',
  'zh-CN': 'zh-CN',
};

export function detectLanguage(deviceLanguages: readonly string[]): Language {
  for (const value of deviceLanguages) {
    const tag = value.trim().replaceAll('_', '-').toLowerCase();
    if (/^zh-(tw|hk|mo|hant)(-|$)/.test(tag)) continue;
    if (tag === 'zh' || /^zh-(cn|sg|hans)(-|$)/.test(tag)) return 'zh-CN';
    const base = tag.split('-')[0];
    if (base === 'en' || base === 'es' || base === 'ht' || base === 'fr') return base;
  }
  return 'en';
}

function isLanguage(value: string | null): value is Language {
  return value !== null && (LANGUAGES as readonly string[]).includes(value);
}

export interface LanguageStorage {
  getItem(key: string): string | null;
  setItem(key: string, value: string): void;
}

interface Localization {
  language: Language;
  locale: string;
  setLanguage(language: Language): void;
  t(key: TranslationKey, params?: Record<string, string | number>): string;
}

const LocalizationContext = createContext<Localization | null>(null);

export function LocalizationProvider({
  children,
  storage,
  deviceLanguages,
}: {
  children: ReactNode;
  storage?: LanguageStorage;
  deviceLanguages?: readonly string[];
}) {
  const store = storage ?? (typeof localStorage === 'undefined' ? undefined : localStorage);
  const detectedLanguages = deviceLanguages ?? (
    typeof navigator === 'undefined' ? [] : [...(navigator.languages ?? []), navigator.language]
  );
  const [language, setCurrentLanguage] = useState<Language>(() => {
    const saved = store?.getItem(LANGUAGE_STORAGE_KEY) ?? null;
    return isLanguage(saved) ? saved : detectLanguage(detectedLanguages);
  });

  const setLanguage = useCallback((value: Language) => {
    store?.setItem(LANGUAGE_STORAGE_KEY, value);
    setCurrentLanguage(value);
  }, [store]);

  const t = useCallback((key: TranslationKey, params: Record<string, string | number> = {}) => (
    messages[language][key].replace(/\{(\w+)\}/g, (placeholder, name: string) => (
      Object.hasOwn(params, name) ? String(params[name]) : placeholder
    ))
  ), [language]);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<Localization>(() => ({
    language,
    locale: localeByLanguage[language],
    setLanguage,
    t,
  }), [language, setLanguage, t]);

  return <LocalizationContext.Provider value={value}>{children}</LocalizationContext.Provider>;
}

export function useLocalization(): Localization {
  const value = useContext(LocalizationContext);
  if (!value) throw new Error('useLocalization must be used inside <LocalizationProvider>');
  return value;
}

export function useDocumentTitle(key: TranslationKey) {
  const { t } = useLocalization();
  const title = t(key);
  useEffect(() => {
    document.title = title;
  }, [title]);
}

